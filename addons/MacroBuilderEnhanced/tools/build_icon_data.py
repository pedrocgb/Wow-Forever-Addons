#!/usr/bin/env python3
"""Generate Data/Icons.lua from the game's own DB2 tables (via wago.tools).

Usage: python3 tools/build_icon_data.py [BUILD]   (default: latest "wowf" = Forever build)
Re-run after a game patch. Output: icon names, class bitmask, item-class bitmask per fileID.
"""
import csv, io, json, os, re, sys, urllib.request

OUT = os.path.join(os.path.dirname(__file__), "..", "Data", "Icons.lua")

def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": "MacroBuilderEnhanced-datagen"})
    return urllib.request.urlopen(req, timeout=120).read().decode("utf-8")

def table(name, build):
    return list(csv.DictReader(io.StringIO(get(f"https://wago.tools/db2/{name}/csv?build={build}"))))

build = sys.argv[1] if len(sys.argv) > 1 else json.loads(get("https://wago.tools/api/builds"))["wowf"][0]["version"]
print("build", build)

# fileID -> name for everything under Interface\Icons\
names = {}
for r in table("ManifestInterfaceData", build):
    if r["FilePath"].lower().rstrip("\\") == "interface\\icons":
        names[int(r["ID"])] = re.sub(r"\.blp$", "", r["FileName"], flags=re.I).lower()

classes = {int(r["ID"]): r["Filename"] for r in table("ChrClasses", build)}  # 1 -> WARRIOR
token_to_bit = {tok.lower(): 1 << (cid - 1) for cid, tok in classes.items()}
WARLOCK_PETS = ("imp", "felhunter", "voidwalker", "succubus", "infernal", "doomguard", "felguard")

# class skill lines -> class mask
skill_lines = {r["ID"]: r for r in table("SkillLine", build)}
line_mask = {}
for r in table("SkillRaceClassInfo", build):
    sl = skill_lines.get(r["SkillID"])
    m = int(r["ClassMask"])
    if sl and sl["CategoryID"] == "7" and m > 0 and m & (m - 1) == 0:  # single class only
        line_mask[r["SkillID"]] = m
pet_families = set()
for sid, sl in skill_lines.items():
    n = sl["DisplayName_lang"].lower()
    if sl["CategoryID"] == "7" and n.startswith("pet - "):
        line_mask[sid] = token_to_bit["warlock" if n[6:] in WARLOCK_PETS else "hunter"]

# [pet:X] compares against CreatureFamily names (e.g. "Crocolisk", while the skill line says "Crocilisk").
for r in table("CreatureFamily", build):
    sl = skill_lines.get(r["SkillLine_0"])
    if sl and sl["DisplayName_lang"].startswith("Pet - ") and "Event" not in sl["DisplayName_lang"]:
        pet_families.add(r["Name_lang"])

spell_mask = {}
for r in table("SkillLineAbility", build):
    m = line_mask.get(r["SkillLine"])
    if m:
        spell_mask[r["Spell"]] = spell_mask.get(r["Spell"], 0) | m

icon_class = {}
for r in table("SpellMisc", build):
    m = spell_mask.get(r["SpellID"])
    icon = int(r["SpellIconFileDataID"])
    if m and icon in names:
        icon_class[icon] = icon_class.get(icon, 0) | m

# Name heuristic: Ability_Warrior_*, ClassIcon_Mage, Spell_Paladin_* ... (covers icons no Forever spell uses)
for fid, n in names.items():
    for tok in n.split("_"):
        if tok in token_to_bit:
            icon_class[fid] = icon_class.get(fid, 0) | token_to_bit[tok]

# item icons -> item class bitmask (bit = ItemClass.ClassID)
icon_item = {}
used_item_classes = set()
for r in table("Item", build):
    icon, cid = int(r["IconFileDataID"]), int(r["ClassID"])
    if icon in names:
        icon_item[icon] = icon_item.get(icon, 0) | (1 << cid)
        used_item_classes.add(cid)

item_classes = [(int(r["ClassID"]), r["ClassName_lang"]) for r in table("ItemClass", build)
                if int(r["ClassID"]) in used_item_classes and "OBSOLETE" not in r["ClassName_lang"]]

def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

with open(OUT, "w", newline="\n") as f:
    f.write(f"-- GENERATED by tools/build_icon_data.py from build {build}. Do not edit.\n")
    f.write("local _, ns = ...\n")
    f.write("ns.ItemClasses = {" + ", ".join(f"{{{cid}, {lua_str(n)}}}" for cid, n in sorted(item_classes)) + "}\n")
    f.write("ns.PetFamilies = {" + ", ".join(lua_str(n) for n in sorted(pet_families)) + "}\n")
    f.write("ns.IconNames = {\n")
    for fid in sorted(names):
        f.write(f"[{fid}]={lua_str(names[fid])},\n")
    f.write("}\nns.IconClass = {\n")
    for fid in sorted(icon_class):
        f.write(f"[{fid}]={icon_class[fid]},\n")
    f.write("}\nns.IconItem = {\n")
    for fid in sorted(icon_item):
        f.write(f"[{fid}]={icon_item[fid]},\n")
    f.write("}\n")

print(f"names={len(names)} class={len(icon_class)} item={len(icon_item)} itemClasses={item_classes}")
